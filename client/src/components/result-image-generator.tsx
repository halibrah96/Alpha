import { useRef } from "react";
import { Card, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Camera, Download } from "lucide-react";
import { useToast } from "@/hooks/use-toast";

interface ResultImageGeneratorProps {
  calculations: {
    csat: string;
    dsat: string;
    ssat: string;
    total: number;
    percentages: number[];
    satisfied: number;
    neutral: number;
    dissatisfied: number;
  };
  ratings: number[];
}

export default function ResultImageGenerator({ calculations, ratings }: ResultImageGeneratorProps) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const { toast } = useToast();

  const generateImage = () => {
    const canvas = canvasRef.current;
    if (!canvas) return;

    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    // Set canvas size
    canvas.width = 800;
    canvas.height = 600;

    // Create gradient background
    const gradient = ctx.createLinearGradient(0, 0, 800, 600);
    gradient.addColorStop(0, '#3B82F6');
    gradient.addColorStop(1, '#8B5CF6');
    ctx.fillStyle = gradient;
    ctx.fillRect(0, 0, 800, 600);

    // Set font styles
    ctx.textAlign = 'center';
    ctx.fillStyle = 'white';

    // Title
    ctx.font = 'bold 36px Arial';
    ctx.fillText('CSAT Analysis Results', 400, 60);

    // Date
    ctx.font = '16px Arial';
    ctx.fillStyle = 'rgba(255, 255, 255, 0.8)';
    ctx.fillText(new Date().toLocaleDateString(), 400, 85);

    // Main metrics container
    ctx.fillStyle = 'rgba(255, 255, 255, 0.1)';
    ctx.roundRect(50, 120, 700, 120, 15);
    ctx.fill();

    // CSAT Score
    ctx.fillStyle = 'white';
    ctx.font = 'bold 28px Arial';
    ctx.fillText('CSAT Score', 200, 160);
    ctx.font = 'bold 48px Arial';
    ctx.fillText(`${calculations.csat}/5.00`, 200, 210);

    // DSAT
    ctx.font = 'bold 28px Arial';
    ctx.fillText('DSAT', 400, 160);
    ctx.font = 'bold 48px Arial';
    ctx.fillStyle = '#EF4444';
    ctx.fillText(`${calculations.dsat}%`, 400, 210);

    // SSAT
    ctx.fillStyle = 'white';
    ctx.font = 'bold 28px Arial';
    ctx.fillText('SSAT', 600, 160);
    ctx.font = 'bold 48px Arial';
    ctx.fillStyle = '#10B981';
    ctx.fillText(`${calculations.ssat}%`, 600, 210);

    // Rating breakdown
    ctx.fillStyle = 'rgba(255, 255, 255, 0.1)';
    ctx.roundRect(50, 270, 700, 200, 15);
    ctx.fill();

    ctx.fillStyle = 'white';
    ctx.font = 'bold 24px Arial';
    ctx.fillText('Rating Breakdown', 400, 305);

    // Rating bars
    const barWidth = 120;
    const barMaxHeight = 100;
    const maxRating = Math.max(...ratings);
    
    const ratingColors = ['#EF4444', '#F97316', '#F59E0B', '#84CC16', '#10B981'];
    const ratingLabels = ['1★', '2★', '3★', '4★', '5★'];

    for (let i = 0; i < 5; i++) {
      const x = 100 + i * 140;
      const barHeight = maxRating > 0 ? (ratings[i] / maxRating) * barMaxHeight : 0;
      
      // Bar
      ctx.fillStyle = ratingColors[i];
      ctx.roundRect(x, 450 - barHeight, barWidth, barHeight, 5);
      ctx.fill();
      
      // Rating label
      ctx.fillStyle = 'white';
      ctx.font = 'bold 18px Arial';
      ctx.fillText(ratingLabels[i], x + barWidth/2, 470);
      
      // Count
      ctx.font = '16px Arial';
      ctx.fillText(ratings[i].toString(), x + barWidth/2, 490);
      
      // Percentage
      ctx.font = '14px Arial';
      ctx.fillStyle = 'rgba(255, 255, 255, 0.8)';
      ctx.fillText(`${calculations.percentages[i].toFixed(1)}%`, x + barWidth/2, 510);
    }

    // Total responses
    ctx.fillStyle = 'white';
    ctx.font = 'bold 20px Arial';
    ctx.fillText(`Total Responses: ${calculations.total}`, 400, 550);

    // Footer
    ctx.font = '14px Arial';
    ctx.fillStyle = 'rgba(255, 255, 255, 0.6)';
    ctx.fillText('Generated by CSAT Calculator Pro', 400, 580);
  };

  const downloadImage = () => {
    generateImage();
    const canvas = canvasRef.current;
    if (!canvas) return;

    // Create download link
    const link = document.createElement('a');
    link.download = `csat-results-${new Date().toISOString().split('T')[0]}.png`;
    link.href = canvas.toDataURL();
    link.click();

    toast({
      title: "Image Downloaded",
      description: "CSAT results image has been saved to your device.",
    });
  };

  const shareImage = async () => {
    generateImage();
    const canvas = canvasRef.current;
    if (!canvas) return;

    try {
      canvas.toBlob(async (blob) => {
        if (!blob) return;

        if (navigator.share && navigator.canShare) {
          const file = new File([blob], 'csat-results.png', { type: 'image/png' });
          
          if (navigator.canShare({ files: [file] })) {
            await navigator.share({
              title: 'CSAT Analysis Results',
              text: `Our latest CSAT score: ${calculations.csat}/5.00`,
              files: [file]
            });
            return;
          }
        }

        // Fallback: copy to clipboard
        if (navigator.clipboard && window.ClipboardItem) {
          await navigator.clipboard.write([
            new ClipboardItem({
              'image/png': blob
            })
          ]);
          
          toast({
            title: "Image Copied",
            description: "CSAT results image copied to clipboard!",
          });
        } else {
          // Final fallback: download
          downloadImage();
        }
      }, 'image/png');
    } catch (error) {
      console.error('Share failed:', error);
      downloadImage();
    }
  };

  return (
    <Card className="bg-gradient-to-br from-purple-50 to-blue-50 dark:from-purple-950 dark:to-blue-950 border-purple-200 dark:border-purple-800">
      <CardContent className="p-6">
        <div className="flex items-center justify-between mb-4">
          <div>
            <h3 className="text-lg font-semibold text-purple-800 dark:text-purple-200">
              Share Results as Image
            </h3>
            <p className="text-sm text-purple-600 dark:text-purple-300">
              Generate a visual summary to share your CSAT analysis
            </p>
          </div>
          <Camera className="w-8 h-8 text-purple-600 dark:text-purple-400" />
        </div>

        <div className="flex gap-3">
          <Button 
            onClick={downloadImage}
            variant="outline"
            className="flex-1 border-purple-300 text-purple-700 hover:bg-purple-50 dark:border-purple-700 dark:text-purple-300 dark:hover:bg-purple-900"
          >
            <Download className="w-4 h-4 mr-2" />
            Download Image
          </Button>
          <Button 
            onClick={shareImage}
            className="flex-1 bg-purple-600 hover:bg-purple-700 text-white"
          >
            <Camera className="w-4 h-4 mr-2" />
            Share Image
          </Button>
        </div>

        {/* Hidden canvas for image generation */}
        <canvas
          ref={canvasRef}
          className="hidden"
          width={800}
          height={600}
        />
      </CardContent>
    </Card>
  );
}